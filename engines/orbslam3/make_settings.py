#!/usr/bin/env python3
"""Write ORB-SLAM3 RGB-D settings for an exported dataset.

Based on ORB-SLAM3's own Examples/RGB-D/RealSense_D435i.yaml (feature settings unchanged);
camera values come from the dataset's calib.yaml:
- intrinsics of the colour camera (depth is aligned to colour), zero distortion as in the export
- Camera.RGB: 0 because cv::imread gives BGR
- RGBD.DepthMapFactor: 5000 (our depth PNG units per metre)
- Stereo.b: the camera's stereo baseline; ThDepth 40 (ORB-SLAM3 default) -> close points < 40 b

Usage: python engines/orbslam3/make_settings.py DATASET OUT.yaml
"""
import os
import sys

import yaml


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    ds, out = sys.argv[1:]
    c = yaml.safe_load(open(os.path.join(ds, "calib.yaml")))
    ci = c["colour"]
    b = float(c.get("stereo_baseline_mm", 50.0)) / 1000.0
    units = float(c.get("depth_png_units_per_m", 5000))
    fps = int(round(float(c.get("fps", 30))))
    txt = f"""%YAML:1.0
# generated by mapping_v2 engines/orbslam3/make_settings.py from {os.path.abspath(ds)}/calib.yaml
File.version: "1.0"
Camera.type: "PinHole"
Camera1.fx: {ci['fx']:.6f}
Camera1.fy: {ci['fy']:.6f}
Camera1.cx: {ci['cx']:.6f}
Camera1.cy: {ci['cy']:.6f}
Camera1.k1: 0.0
Camera1.k2: 0.0
Camera1.p1: 0.0
Camera1.p2: 0.0
Camera.width: {ci['width']}
Camera.height: {ci['height']}
Camera.fps: {fps}
Camera.RGB: 0
Stereo.ThDepth: 40.0
Stereo.b: {b:.6f}
RGBD.DepthMapFactor: {units:.1f}
ORBextractor.nFeatures: 1250
ORBextractor.scaleFactor: 1.2
ORBextractor.nLevels: 8
ORBextractor.iniThFAST: 20
ORBextractor.minThFAST: 7
Viewer.KeyFrameSize: 0.05
Viewer.KeyFrameLineWidth: 1.0
Viewer.GraphLineWidth: 0.9
Viewer.PointSize: 2.0
Viewer.CameraSize: 0.08
Viewer.CameraLineWidth: 3.0
Viewer.ViewpointX: 0.0
Viewer.ViewpointY: -0.7
Viewer.ViewpointZ: -3.5
Viewer.ViewpointF: 500.0
"""
    with open(out, "w") as fh:
        fh.write(txt)
    print(f"ORB-SLAM3 settings -> {out}")


if __name__ == "__main__":
    main()
